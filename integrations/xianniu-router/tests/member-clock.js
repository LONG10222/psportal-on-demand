'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../files/www/luci-static/resources/xianniu_router/member_clock.js'), 'utf8');
const moduleValue = new Function('baseclass', source)({ extend: value => value });
let ms = 0;
const clock = moduleValue.create(() => ms);
assert.equal(clock.read(), null);
const initial = { updated_at: 100, remaining_seconds: 100, pause_state: 1, sample_age_seconds: 4 };
clock.accept(initial);
assert.equal(clock.read().seconds, 96);
ms = 12000;
assert.equal(clock.read().seconds, 84);
clock.accept({ ...initial, sample_age_seconds: 16 });
assert.equal(clock.read().seconds, 84, 'cached status must not reset the countdown');
clock.accept({ updated_at: 99, remaining_seconds: 1000, pause_state: 1 });
assert.equal(clock.read().seconds, 84, 'late old responses must not rewind the balance');
clock.accept({ updated_at: 120, remaining_seconds: 77, pause_state: 1 });
assert.equal(clock.read().seconds, 77, 'fresh official sample corrects local estimate');
ms = 14000;
clock.accept({ updated_at: 122, remaining_seconds: 75, pause_state: 0 });
ms = 40000;
assert.deepEqual(clock.read(), { seconds: 75, estimated: false }, 'paused balance stays fixed');
clock.accept({ updated_at: 150, remaining_seconds: 75, pause_state: 1 });
ms = 50000;
assert.equal(clock.read().seconds, 65, 'resume starts a new countdown');
ms = 500000;
assert.equal(clock.read().seconds, 0, 'never display negative remaining time');
clock.reset();
assert.equal(clock.read(), null);
clock.accept({ updated_at: 1, remaining_seconds: -1 });
assert.equal(clock.read(), null);
console.log('PASS member clock: cached polls, official correction, stale replies, pause/resume, elapsed time, zero clamp');
