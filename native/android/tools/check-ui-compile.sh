# Source/resource validation only. Does not produce a native engine or installable APK.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
: "${ANDROID_JAR:?Set ANDROID_JAR to the licensed SDK platform 36 android.jar}"
: "${AAPT2:?Set AAPT2 to installed Android Build Tools aapt2}"
: "${MOBILE_JAVA:?Set MOBILE_JAVA to Java bindings freshly generated by pinned gobind from native/androidmobile}"
OUT="$ROOT/build/ui-compile"
mkdir -p "$OUT/generated" "$OUT/classes"
"$AAPT2" compile --dir "$ROOT/app/src/main/res" -o "$OUT/resources.zip"
python3 - "$ROOT" "$OUT" <<'PY'
from pathlib import Path
import sys
root, out = map(Path, sys.argv[1:])
# AGP normally supplies the application namespace; reproduce only that merge here.
s = (root/'app/src/main/AndroidManifest.xml').read_text().replace('<manifest xmlns:', '<manifest package="org.psportal.host" xmlns:')
(out/'AndroidManifest.xml').write_text(s)
PY
"$AAPT2" link --manifest "$OUT/AndroidManifest.xml" -I "$ANDROID_JAR" --java "$OUT/generated" \
  --min-sdk-version 26 --target-sdk-version 36 -o "$OUT/resources.apk" "$OUT/resources.zip"
find "$ROOT/app/src/main/java" "$ROOT/app/src/androidTest/java" "$MOBILE_JAVA" "$OUT/generated" -name '*.java' -print > "$OUT/sources.list"
# The installed runtime may include jdk.compiler without the javac launcher.
# This uses actual Android SDK APIs and real generated bindings; no fake native API.
java -m jdk.compiler/com.sun.tools.javac.Main -source 17 -target 17 -classpath "$ANDROID_JAR" \
  -d "$OUT/classes" @"$OUT/sources.list"
echo 'PASS: Android main/test Java source compile, real generated bindings and aapt2 resource link (not APK/runtime validation)'
